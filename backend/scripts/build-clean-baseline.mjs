import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const backendDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDirectory = join(backendDirectory, "supabase", "migrations");
const outputDirectory = join(backendDirectory, "supabase", "baselines");
const baselineVersion = "0018";
const outputPath = join(outputDirectory, `v1_${baselineVersion}_clean.sql`);

const migrationFiles = readdirSync(migrationsDirectory)
  .filter((name) => /^\d{4}_.+\.sql$/.test(name))
  .filter((name) => name.slice(0, 4) <= baselineVersion)
  .sort((left, right) => left.localeCompare(right));

function cleanMigration(name, sql) {
  if (name === "0005_seed.sql") {
    return `-- Clean required bootstrap; intentionally excludes demo catalog data.
insert into public.site_settings
  (id, store_name, currency, currency_symbol, contact_email, shipping_flat, free_shipping_threshold)
values (1, 'Store', 'USD', '$', null, 0, null)
on conflict (id) do nothing;`;
  }

  if (name === "0006_cms.sql") {
    return sql.split("-- Seed default homepage section layout")[0].trimEnd();
  }

  if (name === "0007_page_content.sql") {
    return sql.split("insert into public.content_pages")[0].trimEnd();
  }

  return sql.trimEnd();
}

const header = `-- Reverb storefront clean baseline v1 (covers migrations 0001-0018)
-- Generated by: npm run baseline:build
-- Run once in the Supabase SQL Editor on a new, empty project.
-- This file contains no catalog, branding, legal copy, or credentials.

begin;

select pg_advisory_xact_lock(hashtext('reverb-storefront-clean-baseline-v1'));

do $$
begin
  if to_regclass('public.site_settings') is not null then
    raise exception 'Baseline refused: this project already contains storefront tables';
  end if;
  if exists (select 1 from auth.users limit 1) then
    raise exception 'Baseline refused: create the first administrator only after the baseline succeeds';
  end if;
end
$$;`;

const footer = `-- Neutral defaults for new client stores. Client initialization can replace them.
alter table public.orders
  alter column order_number set default ('ORD-' || nextval('order_number_seq')::text);
alter table public.site_settings
  alter column store_name set default 'Store';
alter table public.email_smtp_settings
  alter column from_name set default 'Store';

update public.site_settings
set store_name = 'Store', contact_email = null
where id = 1;

update public.email_smtp_settings
set from_name = 'Store'
where id = 1;

commit;`;

const sections = migrationFiles.map((name) => {
  const sql = readFileSync(join(migrationsDirectory, name), "utf8");
  return `-- ---------------------------------------------------------------------------\n-- ${name}\n-- ---------------------------------------------------------------------------\n${cleanMigration(name, sql)}`;
});

mkdirSync(outputDirectory, { recursive: true });
writeFileSync(outputPath, `${[header, ...sections, footer].join("\n\n")}\n`);
console.log(`Generated ${outputPath}`);
